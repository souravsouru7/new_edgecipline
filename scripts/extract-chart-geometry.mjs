/**
 * Generates src/components/chart/chart-geometry.ts from the supplied editable
 * chart artwork, so Section 03 can draw a real SVG chart (stroke-on price line,
 * candles arriving left to right, checkpoints pulsing in sequence) instead of
 * animating a flattened bitmap.
 *
 * The source artwork is ~110KB of full-resolution polylines, which is far too
 * much to inline in the page, so this downsamples it:
 *   - the price line keeps every 4th point (max ~4.5px deviation in a 920-unit
 *     viewBox, i.e. well under 2px once rendered)
 *   - the faint "market memory" waves keep every other wave and every 8th point
 *   - candles collapse to one `<body-top-y><u|d>` token each, since their x is a
 *     fixed 23-unit step and their size never changes
 *
 * Run from the project root after the artwork changes:
 *   node scripts/extract-chart-geometry.mjs
 */
import fs from "node:fs";
import path from "node:path";

const SRC = path.join(
  process.cwd(),
  "3/Edgecipline_Chart_Story_4K_Package/assets/02_trading_chart_transparent.svg",
);
const OUT = path.join(process.cwd(), "src/components/chart/chart-geometry.ts");

const LINE_STEP = 4;
const WAVE_STEP = 8;
const WAVE_KEEP_EVERY = 2;
const WAVE_COLORS = ["#09efb2", "#06b2ff", "#a04afe"];

const svg = fs.readFileSync(SRC, "utf8");

const polylines = [...svg.matchAll(/<polyline points="([^"]+)"/g)].map((m) => m[1]);
const parse = (points) => points.trim().split(/\s+/).map((p) => p.split(",").map(Number));
const downsample = (points, step) => {
  const kept = points.filter((_, i) => i % step === 0);
  const last = points[points.length - 1];
  if (kept[kept.length - 1] !== last) kept.push(last);
  return kept;
};
const toPath = (points) => `M${points.map(([x, y]) => `${Math.round(x)} ${Math.round(y)}`).join(" L")}`;

// polylines[0] and [1] are the glow and crisp copies of the same price line.
const priceLine = toPath(downsample(parse(polylines[0]), LINE_STEP));

const waves = polylines
  .slice(2)
  .map((points, index) => ({ index, points }))
  .filter(({ index }) => index % WAVE_KEEP_EVERY === 0)
  .map(({ index, points }) => ({
    color: WAVE_COLORS[index % WAVE_COLORS.length],
    d: toPath(downsample(parse(points), WAVE_STEP)),
  }));

const candles = [
  ...svg.matchAll(
    /<rect x="([\d.]+)" y="([\d.]+)" width="8" height="24" rx="1" fill="(#[0-9a-f]{6})"/g,
  ),
].map((m) => ({ x: Math.round(Number(m[1])), y: Math.round(Number(m[2])), up: m[3] === "#46caff" }));

const checkpoints = [...svg.matchAll(/<circle cx="(\d+)" cy="(\d+)" r="30"/g)].map((m) => ({
  x: Number(m[1]),
  y: Number(m[2]),
}));

const step = candles.length > 1 ? candles[1].x - candles[0].x : 23;

const file = `/**
 * Chart geometry for Section 03, extracted from the supplied editable artwork
 * (3/Edgecipline_Chart_Story_4K_Package/assets/02_trading_chart_transparent.svg)
 * so the chart can be drawn as real SVG instead of a flattened bitmap.
 *
 * Generated by scripts/extract-chart-geometry.mjs — edit the artwork and rerun
 * rather than editing this file.
 * All coordinates live in the artwork's own 3840 x 920 viewBox.
 */

export const CHART_VIEWBOX = { width: 3840, height: 920 } as const;

/** Candle bodies start here and repeat every CANDLE_STEP along x. */
export const CANDLE_X0 = ${candles[0].x};
export const CANDLE_STEP = ${step};
export const CANDLE_BODY = { width: 8, height: 24 } as const;
/** The wick extends this far above and below the body. */
export const CANDLE_WICK_OVERSHOOT = 10;

export const CANDLE_UP = "#46caff";
export const CANDLE_DOWN = "#09e7a8";

/** \`<body-top-y><u|d>\` per candle, left to right. */
const CANDLES_PACKED =
  "${candles.map((c) => `${c.y}${c.up ? "u" : "d"}`).join(" ")}";

export type Candle = { x: number; y: number; up: boolean };

export const CANDLES: Candle[] = CANDLES_PACKED.split(" ").map((token, index) => ({
  x: CANDLE_X0 + index * CANDLE_STEP,
  y: Number(token.slice(0, -1)),
  up: token.endsWith("u"),
}));

/** The price line itself — drawn with a stroke-dash reveal. */
export const PRICE_LINE =
  "${priceLine}";

/** Faint parallel "market memory" waves behind the price line. */
export const ECHO_WAVES: ReadonlyArray<{ d: string; color: string }> = [
${waves.map((w) => `  { color: "${w.color}", d: "${w.d}" },`).join("\n")}
];

/** Emotional checkpoints, in chart coordinates. */
export const CHECKPOINTS: ReadonlyArray<{ x: number; y: number }> = [
${checkpoints.map((c) => `  { x: ${c.x}, y: ${c.y} },`).join("\n")}
];
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, file);
console.log(
  `wrote ${OUT}: ${candles.length} candles, ${waves.length} waves, ${checkpoints.length} checkpoints`,
);
